function clamp(s: string, max: number): string {
  return s.length <= max ? s : s.slice(0, max - 1) + '…';
}

export function runDtrEngine(input: DtrCanonicalInput, options?: DtrEngineRunOptions): DtrEnvelope {
  const idx = options?.stemLaneIndex ?? essenceStemLaneIndex(input.birthDate);
  const stem = TEN_STEM_DISPLAY[idx]!;
  const bodies = STEM_SEED_BODIES[idx]!;
  const nick = input.nickname ? clamp(input.nickname, 20) : 'あなた';

  const s1Overline = input.nickname
    ? `${nick}さんの輪郭`
    : 'この保存版で見えている輪郭';

  const fullSections: DtrSection[] = SECTION_SPECS.map((spec) => {
    if (spec.id === 's8_bridge') {
      const trimmedNick = input.nickname?.trim();
      const mapLeadLine = trimmedNick
        ? `このレポートは、${clamp(trimmedNick, 20)}さん個人の傾向を整理した本質レポートです。`
        : 'このレポートは、個人の傾向を整理した本質レポートです。';
      const narrative = [
        mapLeadLine,
        'どこで力が出やすいか、どこで無理がたまりやすいか、どこから整えると戻りやすいかを、閲覧できる期間内で読み返せます。',
        '追加読み解きでは、この内容をもとに、今気になっていることを具体的に読み直します。',
        'いま何に迷っているのか、どこから整えると楽になりやすいのかを、このレポートに沿って読み直します。',
      ].join('\n\n');
      const body = `${narrative}\n\n${SYSTEM_RULE_COPY}`;
      return {
        id: spec.id,
        title: spec.title,
        summary: spec.teaserSummary,
        body,
        visibility: 'full' as const,
      };
    }

    let body = bodies[spec.bodyKey] as string;

    // AI-generated chapter bodies override seed for s1–s4 (flag-gated; test-injectable).
    // Generated bodies already embed DOB-v2 material, so DOB prefix is skipped for s3.
    if (options?.generatedChapterBodies) {
      const gen = options.generatedChapterBodies;
      if (spec.id === 's1_identity' && gen.s1_identity != null) body = gen.s1_identity;
      else if (spec.id === 's2_composition' && gen.s2_composition != null) body = gen.s2_composition;
      else if (spec.id === 's3_essence' && gen.s3_essence != null) body = gen.s3_essence;
      else if (spec.id === 's4_strengths' && gen.s4_strengths != null) body = gen.s4_strengths;
    }

    if (
      spec.bodyKey === 'composition' &&
      body.includes(STEM3_COMPOSITION_INTRO_TOKEN)
    ) {
      const trimmedNick = input.nickname?.trim();
      const intro = trimmedNick
        ? `${clamp(trimmedNick, 20)}さんは、`
        : 'この保存版で見えている形では、';
      body = body.replace(STEM3_COMPOSITION_INTRO_TOKEN, intro);
    }
    if (
      spec.id === 's1_identity' &&
      idx === 3 &&
      body.includes(STEM3_IDENTITY_INTRO_TOKEN)
    ) {
      const trimmedNick = input.nickname?.trim();
      const idIntro = trimmedNick
        ? `ひとつのことにじっくり向き合うほど、${clamp(trimmedNick, 20)}さんの力は出やすくなります。\n`
        : 'この傾向では、ひとつのことにじっくり向き合うほど、力は出やすくなります。\n';
      const idCore = trimmedNick
        ? `${clamp(trimmedNick, 20)}さん自身が`
        : 'この傾向では、自分自身が';
      body = body
        .replace(STEM3_IDENTITY_INTRO_TOKEN, idIntro)
        .replace(STEM3_IDENTITY_CORE_TOKEN, idCore);
    }
    if (
      spec.id === 's3_essence' &&
      idx === 3 &&
      body.includes(STEM3_ESSENCE_OPEN_TOKEN)
    ) {
      const trimmedNick = input.nickname?.trim();
      const essOpen = trimmedNick
        ? `${clamp(trimmedNick, 20)}さんの力は、`
        : 'この保存版で見えている傾向では、力は、';
      body = body.replace(STEM3_ESSENCE_OPEN_TOKEN, essOpen);
    }
    // DOB-v2 prefix for s1: v2-only (guard is ind.s1IdentityRhythmNote presence; absent in v1).
    // Skip when AI-generated body is supplied (it already embeds DOB material).
    if (spec.id === 's1_identity' && options?.paidIndividualization && !options.generatedChapterBodies?.s1_identity) {
      body = buildPaidDtrSectionIndividualizationPrefix(spec.id, options.paidIndividualization) + body;
    }
    // DOB-v2 prefix for s2: v2-only (guard is ind.s2CompositionRhythmNote presence).
    if (spec.id === 's2_composition' && options?.paidIndividualization && !options.generatedChapterBodies?.s2_composition) {
      body = buildPaidDtrSectionIndividualizationPrefix(spec.id, options.paidIndividualization) + body;
    }
    // DOB-v2 prefix for s3: skip when a generated body is supplied (it already embeds DOB material).
    if (spec.id === 's3_essence' && options?.paidIndividualization && !options.generatedChapterBodies?.s3_essence) {
      body = buildPaidDtrSectionIndividualizationPrefix(spec.id, options.paidIndividualization) + body;
    }
    // DOB-v2 prefix for s4: v2-only (guard is ind.s4StrengthsRhythmNote presence).
    if (spec.id === 's4_strengths' && options?.paidIndividualization && !options.generatedChapterBodies?.s4_strengths) {
      body = buildPaidDtrSectionIndividualizationPrefix(spec.id, options.paidIndividualization) + body;
    }
    if (spec.id === 's5_friction' && options?.paidIndividualization) {
      body = buildPaidDtrSectionIndividualizationPrefix(spec.id, options.paidIndividualization) + body;
    }
    if (spec.id === 's6_relation' && options?.paidIndividualization) {
      body = buildPaidDtrSectionIndividualizationPrefix(spec.id, options.paidIndividualization) + body;
    }
    if (spec.id === 's7_work' && options?.paidIndividualization) {
      body = buildPaidDtrSectionIndividualizationPrefix(spec.id, options.paidIndividualization) + body;
    }
    const title =
      spec.id === 's1_identity'  ? s1Overline :
      spec.id === 's4_strengths' ? '力が出やすい場面' :
      spec.title;
    return {
      id: spec.id,
      title,
      summary: spec.teaserSummary,
      body,
      visibility: 'full' as const,
    };
  });

  const teaserSections: DtrSection[] = SECTION_SPECS.map((spec) => ({
    id: spec.id,
    title: spec.title,
    summary: spec.teaserSummary,
    body: '',
    visibility: 'teaser' as const,
  }));

  const payload: DtrPayload = {
    title: `${LABEL_SAVED_REPORT_MY_JP} — ${nick}さんの取り扱い説明書`,
    teaserSections,
    fullSections,
    ownershipType: 'static',
    expiresAt: null,
    aiConsultIncluded: true,
    version: 'v1',
  };

  const auditMeta: DtrAuditMeta = {
    stemLaneIndex: idx,
    stemChar: stem.stemChar,
    derivation: options?.derivation ?? 'jdn_offset_provisional_v1',
    ...(options?.paidIndividualization
      ? { paidIndividualization: toComposedPaidDtrIndividualizationAuditMeta(options.paidIndividualization) }
      : {}),
  };

  return {
    contractVersion: options?.contractVersion ?? 'v1',
    engineVersion: options?.engineVersion ?? 'dtr-v1-jdn-day-stem-provisional',
    generatedAt: new Date().toISOString(),
    payload,
    auditMeta,
  };
}
