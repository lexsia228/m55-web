function clamp(s: string, max: number): string {
  return s.length <= max ? s : s.slice(0, max - 1) + '…';
}

export function runDtrEngine(input: DtrCanonicalInput): DtrEnvelope {
  const idx = essenceStemLaneIndex(input.birthDate);
  const stem = TEN_STEM_DISPLAY[idx]!;
  const bodies = STEM_BODIES[idx]!;
  const nick = input.nickname ? clamp(input.nickname, 20) : 'あなた';

  const fullSections: DtrSection[] = SECTION_SPECS.map((spec) => {
    let body = bodies[spec.bodyKey] as string;
    if (spec.id === 's8_bridge') {
      body = `${body}\n\n${SYSTEM_RULE_COPY}`;
    }
    return {
      id: spec.id,
      title: spec.title,
      summary: spec.teaserSummary,
      body,
      visibility: 'full' as const,
    };
  });

  const teaserSections: DtrSection[] = SECTION_SPECS.map((spec) => ({
    id: spec.id,
    title: spec.title,
    summary: spec.teaserSummary,
    body: '',
    visibility: 'teaser' as const,
  }));

  const payload: DtrPayload = {
    title: `Entry Report — ${nick}さんの取り扱い説明書`,
    teaserSections,
    fullSections,
    ownershipType: 'static',
    expiresAt: null,
    aiConsultIncluded: true,
    version: 'v1',
  };

  const auditMeta: DtrAuditMeta = {
    stemLaneIndex: idx,
    stemChar: stem.stemChar,
    derivation: 'jdn_offset_provisional_v1',
  };

  return {
    contractVersion: 'v1',
    engineVersion: 'dtr-v1-jdn-day-stem-provisional',
    generatedAt: new Date().toISOString(),
    payload,
    auditMeta,
  };
}
